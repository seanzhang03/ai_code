# 索引访问
#下标访问和切片访问
str = "zhangyang"
#下标访问
print(str[2],end=" ")
#切片访问 字符串名[初始位置:终止位置:步长]，默认包括初始位置但是不包括结束位置，步长默认为1，没给初始位置
#则默认开始位置为初始位置，没给终止位置则默认结束位置为终止位置
print(str[0:5:1])
print(str[::]) #没给终止位置，则会默认输出整个字符串
print(str[0:4:2]) #只打印2个字符，实际上打印下标为0和2的字符
print(str[::-1]) #倒序输出字符串,-1时默认为倒序输出
print(str[8:-1:-1]) #不能这么做的原因是-1这个下标也有实际含义,步长为负数的时候，终止位置要在起始位置的左侧，这里8和-1是同一个数，即[8,8)

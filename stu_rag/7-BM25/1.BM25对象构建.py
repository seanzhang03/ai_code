#对于上述文本中，我们就需要把他进行分词处理，注意事项：
#1.分词后的语气词不重要，可能会对结果产生影响，我们直接过滤

#分词库
import  jieba

#BM25对象构建类
from rank_bm25 import BM25Okapi

#定义分词函数
def tokenize(text):
    data=[]
    for item in list(jieba.cut(text)):
        if item in STOP_WORDS or len(item.strip())==0:
            continue
        data.append(item)
        #返回的是一个列表
    return data
    #return [item for item in list(jieba.cut(text)) if item not in STOP_WORDS and len(item.strip())>0]

#定义停顿词
STOP_WORDS = set([
    "的", "了", "在", "是", "我", "有", "和", "就", "不", "人", "都",
    "一", "一个", "上", "也", "很", "到", "说", "要", "去", "你", "会",
    "着", "没有", "看", "好", "自己", "这", "那", "他", "她", "它", "们",
    "这个", "那个", "什么", "哪", "怎么", "吗", "呢", "吧", "啊", "哦",
    "还", "被", "把", "让", "从", "对", "与", "但", "而", "或", "所",
    "为", "以", "及", "可", "可以", "能", "能够", "应该", "需要", "已经",
    "虽然", "如果", "因为", "所以", "只是", "还是", "不过", "然后",
    "之", "其", "中", "等", "等等", "即", "使", "向", "将", "按", "当",
    "于", "由", "比", "除了", "关于", "以及", "并且", "此外", "另外",
    "过", "着", "来", "去", "做", "作", "像", "如", "如同", "由于",
])

#分词测试
results = [tokenize(item) for item in documents]

#创建BM25对象
bm25=BM25Okapi(results)
print(bm25)

#准备测试用例
